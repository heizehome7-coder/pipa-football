/**
 * Bundles the shared penalty judge (the same TypeScript the browser runs) into a
 * plain ESM module the Render server can import: server/judge.gen.mjs.
 * Runs as part of `npm run build`.
 */
import { build } from 'esbuild';

await build({
  entryPoints: ['src/online/match/judge.ts'],
  outfile: 'server/judge.gen.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  external: ['three'],
  logLevel: 'warning',
  banner: { js: '// generated by scripts/build-server.mjs — do not edit' },
});
console.log('server judge → server/judge.gen.mjs');
